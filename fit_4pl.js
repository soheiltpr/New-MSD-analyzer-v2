function weights1OverY2(signals) {
  return signals.map(y => 1 / Math.pow(Math.max(y, 1e-6), 2));
}

function fitAnalyte({ name, standards }) {
  const xs = standards.map(([conc]) => conc);
  const ys = standards.map(([, signal]) => signal);

  const minSignal = Math.min(...ys);
  const maxSignal = Math.max(...ys);
  const positiveXs = xs.filter(x => x > 0);
  const minX = Math.min(...positiveXs);
  const maxX = Math.max(...positiveXs);

  const D0 = Math.min(minSignal * 0.9, minSignal - 10);
  const A0 = maxSignal * 1.5;

  const target = D0 + 0.5 * (A0 - D0);
  let bestIndex = 0;
  let bestDiff = Math.abs(ys[0] - target);
  for (let i = 1; i < ys.length; i++) {
    const diff = Math.abs(ys[i] - target);
    if (diff < bestDiff) {
      bestDiff = diff;
      bestIndex = i;
    }
  }
  const C0 = Math.max(xs[bestIndex], EPS);
  const B0 = 1.0;

  const initialValues = [A0, B0, C0, D0];
  const minValues = [
    maxSignal * 0.1,
    0.2,
    Math.max(minX / 1000, EPS),
    Math.max(minSignal - maxSignal, -1e6),
  ];
  const maxValues = [
    maxSignal * 1e3,
    3.0,
    maxX * 1e3,
    minSignal,
  ];

  const weights = weights1OverY2(ys);

  const model = ([A, B, C, D]) => x => {
    const xSafe = Math.max(x, EPS);
    const term = Math.pow(C / xSafe, B);
    return D + (A - D) / (1 + term);
  };

  const result = levenbergMarquardt(
    { x: xs, y: ys },
    model,
    {
      initialValues,
      minValues,
      maxValues,
      weights,
      damping: 1e-2,
      gradientDifference: EPS,
      maxIterations: 500,
      errorTolerance: 1e-12,
    }
  );

  const [A, B, C, D] = result.parameterValues;

  const fn = model(result.parameterValues);
  const meanY = ys.reduce((sum, v) => sum + v, 0) / ys.length;
  let ssRes = 0;
  let ssTot = 0;
  ys.forEach((y, i) => {
    const residual = y - fn(xs[i]);
    ssRes += residual * residual;
    const diff = y - meanY;
    ssTot += diff * diff;
  });
  const rSquared = 1 - ssRes / ssTot;

  return {
    name,
    iterations: result.iterations,
    params: { A, B, C, D },
    rSquared,
  };
}

function main() {
  console.log('Analyte\tIterations\tR^2\tTop(A)\tBottom(D)\tMidPoint(C)\tHillSlope(B)');
  for (const dataset of getDatasets()) {
    const { name, iterations, params, rSquared } = fitAnalyte(dataset);
    console.log(
      `${name}\t${iterations}\t${rSquared.toFixed(6)}\t${params.A}\t${params.D}\t${params.C}\t${params.B}`
    );
  }
}

main();
